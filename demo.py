def demo_document(idea):
    topic = idea.strip().split("\n")[0][:80]
    chapters = []
    for title, intro, sections in CH:
        blocks = [("p", intro.format(topic=topic))]
        for h, p in sections:
            blocks += [("h2", h), ("p", p)]
        chapters.append({"title": title, "blocks": blocks})
    return {
        "title": topic,
        "subtitle": "نموذج تجريبي بنص جاهز (دون اتصال بنموذج الذكاء الاصطناعي)",
        "chapters": chapters,
    }

